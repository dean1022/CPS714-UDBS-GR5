CREATE TABLE IF NOT EXISTS library_user (                      -- one row per library user (students and faculty)
    user_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,  -- unique id, SQLite picks the number for us
    university_id  TEXT NOT NULL UNIQUE,               -- the ID they log in with, e.g. S1001
    first_name     TEXT NOT NULL,                      -- first name (comes from the university)
    last_name      TEXT NOT NULL,                      -- last name (comes from the university)
    email          TEXT NOT NULL UNIQUE,               -- email (comes from the university)
    phone          TEXT,                               -- phone number (the user can edit this)
    address        TEXT,                               -- address (the user can edit this)
    role           TEXT NOT NULL DEFAULT 'USER',       -- 'USER' or 'ADMIN'
    max_loans      INTEGER NOT NULL DEFAULT 150,         -- how many books they may borrow at once
    max_holds      INTEGER NOT NULL DEFAULT 3,         -- how many holds they may have at once
    created_at     TEXT NOT NULL                       -- when the account was created
);

CREATE TABLE IF NOT EXISTS session (                   -- one row each time someone logs in
    session_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,    -- unique id of this login
    user_id      INTEGER NOT NULL REFERENCES library_user(user_id),  -- who logged in
    login_time   TEXT NOT NULL,                        -- when they logged in
    logout_time  TEXT                                  -- when they logged out (empty while logged in)
);

CREATE TABLE IF NOT EXISTS category (                  -- e.g. 'Computer Science', 'History'
    category_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,    -- unique id
    name         TEXT NOT NULL UNIQUE                  -- the category name
);

CREATE TABLE IF NOT EXISTS author (                    -- people who wrote the books
    author_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,      -- unique id
    name       TEXT NOT NULL UNIQUE                    -- full name, e.g. 'Stephen Hawking'
);

CREATE TABLE IF NOT EXISTS keyword (                   -- search words, e.g. 'databases'
    keyword_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,     -- unique id
    word        TEXT NOT NULL UNIQUE                   -- the word itself
);

CREATE TABLE IF NOT EXISTS literature (                -- one row per e-book in the catalogue
    literature_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,  -- unique id
    category_id         INTEGER NOT NULL REFERENCES category(category_id),  -- which category it's in
    title               TEXT NOT NULL,                 -- book title
    publication_year    INTEGER,                       -- year it was published
    file_url            TEXT NOT NULL,                 -- where the e-book file lives (what "reading" opens)
    total_access_slots  INTEGER NOT NULL,              -- how many people can borrow it at the same time
    summary             TEXT,
    loan_period_days    INTEGER NOT NULL DEFAULT 14    -- how long one loan lasts
);

CREATE TABLE IF NOT EXISTS literature_author (         -- link table: a book can have many authors
    literature_id  INTEGER NOT NULL REFERENCES literature(literature_id),  -- the book
    author_id      INTEGER NOT NULL REFERENCES author(author_id),          -- one of its authors
    PRIMARY KEY (literature_id, author_id)             -- the same pair can't be added twice
);

CREATE TABLE IF NOT EXISTS literature_keyword (        -- link table: a book can have many keywords
    literature_id  INTEGER NOT NULL REFERENCES literature(literature_id),  -- the book
    keyword_id     INTEGER NOT NULL REFERENCES keyword(keyword_id),        -- one of its keywords
    PRIMARY KEY (literature_id, keyword_id)            -- the same pair can't be added twice
);

CREATE TABLE IF NOT EXISTS hold (                      -- a place in line for a book that is fully borrowed
    hold_id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,  -- unique id
    user_id            INTEGER NOT NULL REFERENCES library_user(user_id),                -- who is waiting
    literature_id      INTEGER NOT NULL REFERENCES literature(literature_id),    -- which book
    placed_at          TEXT NOT NULL,                  -- when they joined the line
    queue_position     INTEGER,                        -- 1 = next in line (empty once it's READY)
    status             TEXT NOT NULL DEFAULT 'WAITING',  -- WAITING, READY, ACCEPTED, DECLINED, EXPIRED, CANCELLED
    ready_at           TEXT,                           -- when the book became free for them
    decision_deadline  TEXT                            -- ready_at + 72 hours
);

CREATE TABLE IF NOT EXISTS loan (                      -- one row each time someone borrows a book
    loan_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,  -- unique id
    user_id        INTEGER NOT NULL REFERENCES library_user(user_id),              -- who borrowed it
    literature_id  INTEGER NOT NULL REFERENCES literature(literature_id),  -- which book
    hold_id        INTEGER REFERENCES hold(hold_id),   -- the hold it came from (empty if borrowed directly)
    borrowed_at    TEXT NOT NULL,                      -- when it was borrowed
    due_at         TEXT NOT NULL,                      -- when it will be returned automatically
    returned_at    TEXT,                               -- when it was actually returned (empty while active)
    return_type    TEXT,                               -- 'EARLY' (user returned it) or 'AUTO' (it expired)
    renewal_count  INTEGER NOT NULL DEFAULT 0,         -- how many times it has been renewed
    status         TEXT NOT NULL DEFAULT 'ACTIVE'      -- 'ACTIVE' or 'RETURNED'
);

CREATE TABLE IF NOT EXISTS notification (              -- messages shown to the user
    notification_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,  -- unique id
    user_id          INTEGER NOT NULL REFERENCES library_user(user_id),  -- who the message is for
    loan_id          INTEGER REFERENCES loan(loan_id), -- the loan it's about (optional)
    hold_id          INTEGER REFERENCES hold(hold_id), -- the hold it's about (optional)
    type             TEXT NOT NULL,                    -- e.g. HOLD_READY, BORROW_SUCCESS, ERROR
    message          TEXT NOT NULL,                    -- the text the user reads
    created_at       TEXT NOT NULL,                    -- when it was sent
    is_read          INTEGER NOT NULL DEFAULT 0        -- 0 = unread, 1 = read
);

CREATE TABLE IF NOT EXISTS users (university_id TEXT PRIMARY KEY, email TEXT NOT NULL UNIQUE, password_hash TEXT NOT NULL, first_name TEXT NOT NULL, last_name TEXT NOT NULL, display_name TEXT NOT NULL, pronouns TEXT, status TEXT NOT NULL CHECK(status IN ('student','faculty')));
CREATE TABLE IF NOT EXISTS sessions(token TEXT PRIMARY KEY, university_id TEXT NOT NULL REFERENCES users(university_id), created_at TEXT NOT NULL, expires_at TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS loan_active_idx ON loan (user_id, literature_id, status);
CREATE INDEX IF NOT EXISTS hold_queue_idx ON hold (literature_id, status, queue_position);
